/* times x in GF(2^8) modulo x^8 + x^4 + x^3 + x + 1, without a branch */
static u8 xtime(u8 x) { return (u8)((x << 1) ^ (0x1b & -(x >> 7))); }

static u32 get_be32(const u8 *p) { return ((u32)p[0] << 24) | ((u32)p[1] << 16) | ((u32)p[2] << 8) | p[3]; }

void aes128_setkey(struct aes_ctx *ctx, const u8 key[16]) {
    u32 *w = ctx->rk, t;
    u8 rcon = 1;
    int i, r;
    for(i = 0; i < 4; i++) w[i] = get_be32(key + 4 * i);
    for(i = 4; i < 44; i++) {
        t = w[i - 1];
        if(!(i & 3)) {                  /* SubWord(RotWord(t)) xor Rcon */
            t = ((u32)sbox[(t >> 16) & 0xff] << 24) | ((u32)sbox[(t >> 8) & 0xff] << 16) |
                ((u32)sbox[t & 0xff] << 8) | sbox[t >> 24];
            t ^= (u32)rcon << 24;
            rcon = xtime(rcon);
        }
        w[i] = w[i - 4] ^ t;
    }
    for(r = 0; r <= 10; r++)
        for(i = 0; i < 4; i++) ctx->drk[4 * r + i] = w[4 * (10 - r) + i];
}

static void add_round_key(u8 s[16], const u32 *k) {
    int c;
    for(c = 0; c < 4; c++) {
        s[4 * c] ^= (u8)(k[c] >> 24);
        s[4 * c + 1] ^= (u8)(k[c] >> 16);
        s[4 * c + 2] ^= (u8)(k[c] >> 8);
        s[4 * c + 3] ^= (u8)k[c];
    }
}

/* SubBytes, then ShiftRows: row r turns r columns to the left (byte r + 4c is row r, column c) */
static void sub_shift(u8 s[16]) {
    u8 t;
    int i;
    for(i = 0; i < 16; i++) s[i] = sbox[s[i]];
    t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = s[3]; s[3] = t;
}

static void inv_shift_sub(u8 s[16]) {
    u8 t;
    int i;
    t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[3]; s[3] = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = t;
    for(i = 0; i < 16; i++) s[i] = inv_sbox[s[i]];
}

/* each column times 3x^3 + x^2 + x + 2: s0' = 2a0 ^ 3a1 ^ a2 ^ a3 = a0 ^ x ^ 2(a0 ^ a1) with x = a0 ^ a1 ^ a2 ^ a3 */
static void mix_columns(u8 s[16]) {
    u8 a0, a1, a2, a3, x;
    int c;
    for(c = 0; c < 16; c += 4) {
        a0 = s[c]; a1 = s[c + 1]; a2 = s[c + 2]; a3 = s[c + 3];
        x = a0 ^ a1 ^ a2 ^ a3;
        s[c] = a0 ^ x ^ xtime(a0 ^ a1);
        s[c + 1] = a1 ^ x ^ xtime(a1 ^ a2);
        s[c + 2] = a2 ^ x ^ xtime(a2 ^ a3);
        s[c + 3] = a3 ^ x ^ xtime(a3 ^ a0);
    }
}

/* the inverse, 0bx^3 + 0dx^2 + 09x + 0e, is MixColumns after a multiplication by 04x^2 + 05 */
static void inv_mix_columns(u8 s[16]) {
    u8 u, v;
    int c;
    for(c = 0; c < 16; c += 4) {
        u = xtime(xtime(s[c] ^ s[c + 2]));
        v = xtime(xtime(s[c + 1] ^ s[c + 3]));
        s[c] ^= u;
        s[c + 1] ^= v;
        s[c + 2] ^= u;
        s[c + 3] ^= v;
    }
    mix_columns(s);
}

void aes128_encrypt(const struct aes_ctx *ctx, const u8 in[AES_BLOCK], u8 out[AES_BLOCK]) {
    u8 s[16];
    int r;
    memcpy(s, in, 16);
    add_round_key(s, ctx->rk);
    for(r = 1; r < 10; r++) {
        sub_shift(s);
        mix_columns(s);
        add_round_key(s, ctx->rk + 4 * r);
    }
    sub_shift(s);
    add_round_key(s, ctx->rk + 40);
    memcpy(out, s, 16);
    crypto_wipe(s, sizeof(s));
}

void aes128_decrypt(const struct aes_ctx *ctx, const u8 in[AES_BLOCK], u8 out[AES_BLOCK]) {
    u8 s[16];
    int r;
    memcpy(s, in, 16);
    add_round_key(s, ctx->drk);
    for(r = 1; r < 10; r++) {
        inv_shift_sub(s);
        add_round_key(s, ctx->drk + 4 * r);
        inv_mix_columns(s);
    }
    inv_shift_sub(s);
    add_round_key(s, ctx->drk + 40);
    memcpy(out, s, 16);
    crypto_wipe(s, sizeof(s));
}

/**** AES key wrap (RFC 3394 2.2.1 and 2.2.2, the index-based form) ****/

static const u8 wrap_iv[8] = { 0xa6, 0xa6, 0xa6, 0xa6, 0xa6, 0xa6, 0xa6, 0xa6 };

/* A ^= t, t a 64-bit big-endian counter (it never reaches 2^32 here) */
static void xor_counter(u8 a[8], u32 t) {
    a[4] ^= (u8)(t >> 24);
    a[5] ^= (u8)(t >> 16);
    a[6] ^= (u8)(t >> 8);
    a[7] ^= (u8)t;
}

void aes_wrap(const u8 kek[16], const u8 *plain, size_t plain_len, u8 *wrapped) {
    struct aes_ctx ctx;
    u8 b[16];                           /* A || R[i] going in, B coming out */
    size_t n, i;
    u_int j;
    if(plain_len % 8 || plain_len < 16) return;
    n = plain_len / 8;
    aes128_setkey(&ctx, kek);
    memcpy(b, wrap_iv, 8);
    memcpy(wrapped + 8, plain, plain_len);
    for(j = 0; j < 6; j++) {
        for(i = 1; i <= n; i++) {
            memcpy(b + 8, wrapped + 8 * i, 8);
            aes128_encrypt(&ctx, b, b);
            xor_counter(b, (u32)(n * j + i));
            memcpy(wrapped + 8 * i, b + 8, 8);
        }
    }
    memcpy(wrapped, b, 8);
    crypto_wipe(&ctx, sizeof(ctx));
    crypto_wipe(b, sizeof(b));
}

int aes_unwrap(const u8 kek[16], const u8 *wrapped, size_t wrapped_len, u8 *plain) {
    struct aes_ctx ctx;
    u8 b[16];
    size_t n, i;
    u_int j;
    bool ok;
    if(wrapped_len % 8 || wrapped_len < 24) return -1;
    n = wrapped_len / 8 - 1;
    aes128_setkey(&ctx, kek);
    memcpy(b, wrapped, 8);
    memcpy(plain, wrapped + 8, 8 * n);
    for(j = 6; j-- > 0; ) {
        for(i = n; i >= 1; i--) {
            xor_counter(b, (u32)(n * j + i));
            memcpy(b + 8, plain + 8 * (i - 1), 8);
            aes128_decrypt(&ctx, b, b);
            memcpy(plain + 8 * (i - 1), b + 8, 8);
        }
    }
    ok = crypto_equal(b, wrap_iv, 8);
    if(!ok) crypto_wipe(plain, 8 * n);
    crypto_wipe(&ctx, sizeof(ctx));
    crypto_wipe(b, sizeof(b));
    return ok ? 0 : -1;
}
