#!/usr/bin/env python3
"""
SurfCPU generated test: every M instruction on every pair of edge values
--------------------
File: gen_muldiv.py Date: 10/15/26 (SurfCPU)
--------------------
Writes muldiv_edges.S (to stdout): MUL, MULH, MULHSU, MULHU, DIV, DIVU, REM and REMU on
every ordered pair of 16 edge values plus seeded random pairs, each checked against the
result the RISC-V M specification defines, computed here independently of the RTL.

    gen_muldiv.py > build/cpu/gen/muldiv_edges.S
"""

from __future__ import annotations

import random
import sys

M32 = 0xFFFFFFFF
EDGES = [0x00000000, 0x00000001, 0x00000002, 0x00000003, 0x00000007, 0xFFFFFFFF, 0xFFFFFFFE,
         0xFFFFFFF9, 0x7FFFFFFF, 0x80000000, 0x80000001, 0x0000FFFF, 0xFFFF0000, 0x00010000,
         0x12345678, 0xEDCBA987]


def s32(x: int) -> int:
    return x - (1 << 32) if x & 0x80000000 else x


def trunc_div(a: int, b: int) -> int:
    q = abs(a) // abs(b)
    return -q if (a < 0) != (b < 0) else q


def ref(op: str, a: int, b: int) -> int:
    sa, sb = s32(a), s32(b)
    if op == "mul":
        return (a * b) & M32
    if op == "mulh":
        return ((sa * sb) >> 32) & M32
    if op == "mulhsu":
        return ((sa * b) >> 32) & M32
    if op == "mulhu":
        return ((a * b) >> 32) & M32
    if op == "div":
        if b == 0:
            return M32
        if sa == -(1 << 31) and sb == -1:
            return 0x80000000
        return trunc_div(sa, sb) & M32
    if op == "divu":
        return M32 if b == 0 else a // b
    if op == "rem":
        if b == 0:
            return a
        if sa == -(1 << 31) and sb == -1:
            return 0
        return (sa - trunc_div(sa, sb) * sb) & M32
    if op == "remu":
        return a if b == 0 else a % b
    raise ValueError(op)


def main() -> int:
    rng = random.Random(20261015)
    pairs = [(a, b) for a in EDGES for b in EDGES]
    pairs += [(rng.getrandbits(32), rng.getrandbits(32)) for _ in range(24)]
    pairs += [(rng.getrandbits(32), rng.getrandbits(rng.choice([4, 8, 16]))) for _ in range(24)]
    ops = ["mul", "mulh", "mulhsu", "mulhu", "div", "divu", "rem", "remu"]
    out = ["/* Generated by sim/cpu/tests/gen_muldiv.py -- do not edit. */",
           '#include "surf_test.h"', "TEST_BEGIN", "test_main:"]
    num = 1
    for op in ops:
        for a, b in pairs:
            out.append(f"        TEST_RR({num}, {op}, 0x{ref(op, a, b):08x}, 0x{a:08x}, 0x{b:08x})")
            num += 1
    out += ["        j       pass", "TEST_DATA", ""]
    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
