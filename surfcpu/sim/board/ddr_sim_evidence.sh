#!/bin/sh
# SurfCPU board track: the DDR designs in simulation, for the record. On the Mac, from surfcpu/,
# with Docker, on a committed tree (the ROMs carry the commit). Nothing is programmed.
#   1. make board-ddr-sim BOARD=arty_a7_100t: the DDR top in RTL with LiteDRAM's controller and
#      DRAM model (the BRAM diagnostics and SurfBoot, each initializing it through the ddrc
#      registers) and with the generated board core (controller and PHY, no CPU) and no memory
#      (sim/board/ddr_top_sim.sh);
#   2. make board-uart-expect-ddr BOARD=arty_a7_100t: SurfBoot booting SurfOS with the C++ DDR
#      model and LiteDRAM's register model (sim/board/uart_expect_ddr.sh);
#   3. with DDR_SIM_NETLIST=1, or alone with --netlist-only, make board-netlist-sim
#      BOARD=arty_a7_100t DESIGN=surfcpu_arty_a7_ddr_bramdiag: the synthesized netlist of the last
#      open-flow build of that design, from its pins, with no memory (about an hour). A run
#      without it keeps the last netlist simulation's record, which names its own source.
# Writes docs/evidence/ddr/ddr-top-sim.txt and docs/evidence/board/uart-expect-ddr.txt.
# --report-only writes them again from the last run's outputs.
set -eu
mode=run
case "${1:-}" in --report-only) mode=report ;; --netlist-only) mode=netlist ;; esac
board=arty_a7_100t
t=build/sim/board/ddr_sim_evidence
out=docs/evidence/ddr/ddr-top-sim.txt
uout=docs/evidence/board/uart-expect-ddr.txt
rev=$(git rev-parse --short=12 HEAD)
state=clean
[ -z "$(git status --porcelain)" ] || state="dirty (uncommitted changes)"
started=$(date +%s)
d=build/sim/board/ddr_top

netlist() {        # the post-synthesis simulation, into $t/netlist.*
    rm -f "$t"/netlist*
    n0=$(date +%s)
    echo "$rev ($state)" > "$t/netlist.source"
    if make --no-print-directory board-netlist-sim BOARD=$board DESIGN=surfcpu_arty_a7_ddr_bramdiag \
           > "$t/netlist.txt" 2>&1; then rc=0; else rc=$?; fi
    echo "$rc" > "$t/netlist.rc"
    echo "$(( ($(date +%s) - n0) / 60 ))" > "$t/netlist.minutes"
}
if [ "$mode" = run ]; then
    if [ "${DDR_SIM_NETLIST:-0}" = 1 ]; then
        rm -rf "$t"
    elif [ -d "$t" ]; then           # keep the last netlist simulation's record
        find "$t" -mindepth 1 -maxdepth 1 ! -name 'netlist*' -exec rm -rf {} +
    fi
    mkdir -p "$t"
    echo "$rev ($state)" > "$t/source"
    if make --no-print-directory board-ddr-sim BOARD=$board > "$t/board-ddr-sim.txt" 2>&1; then rc=0; else rc=$?; fi
    echo "$rc" > "$t/board-ddr-sim.rc"
    if make --no-print-directory board-uart-expect-ddr BOARD=$board > "$t/uart-expect-ddr.txt" 2>&1; then rc=0; else rc=$?; fi
    echo "$rc" > "$t/uart-expect-ddr.rc"
    [ "${DDR_SIM_NETLIST:-0}" != 1 ] || netlist
    echo "$(( ($(date +%s) - started) / 60 ))" > "$t/minutes"
elif [ "$mode" = netlist ]; then
    mkdir -p "$t"
    netlist
    echo "ddr_sim_evidence: netlist simulation exit $(cat "$t/netlist.rc") (records written by the next run or --report-only)"
    exit 0
fi
[ -f "$t/minutes" ] || { echo "ddr_sim_evidence: no complete run in $t" >&2; exit 1; }

run() {           # DIR TITLE: one ddr_top_sim run
    echo
    echo "== $2"
    echo "   ($1)"
    grep -E 'tb_netlist: [0-9]+ lines|tb_netlist: LEDs|memory controller.s console|VGA hsync|Verilator: \$finish|walltime' "$1/run.txt" | sed 's/^/  /'
    echo "  the SoC's UART (115200 8N1), with the time each line ended:"
    grep 'uart|' "$1/run.txt" | sed -e 's/^tb_netlist: */  /' -e 's/ uart| / | /'
}
{
    echo "SurfCPU ddr track evidence: the DDR designs' top in simulation, EXPECTED BEHAVIOUR, never"
    echo "observed on a board. Generated by sim/board/ddr_sim_evidence.sh on $(date -u +%Y-%m-%d) at source"
    echo "$(cat "$t/source"), in $(cat "$t/minutes") minutes. No DDR3 memory model is used anywhere: real"
    echo "calibration can only happen on the board."
    echo
    echo "make board-ddr-sim BOARD=$board: exit $(cat "$t/board-ddr-sim.rc")"
    grep -E '^ddr_top_sim: (surfcpu|litedram_core)' "$t/board-ddr-sim.txt" | sort -u | sed 's/^/  /'
    run "$d/$board-bramdiag-model" "the BRAM diagnostics with LiteDRAM's controller and DRAM model, which they initialize (its model PHY has no delays to level)"
    run "$d/$board-surfboot-model" "SurfBoot with LiteDRAM's controller and DRAM model, which it initializes; no card"
    run "$d/$board-bramdiag-board" "the BRAM diagnostics with the generated board core (controller and A7DDRPHY, no CPU; models of its primitives), nothing on the DDR3L pins"
    if [ -f "$t/netlist.rc" ]; then
        m=build/fpga/$board/surfcpu_arty_a7_ddr_bramdiag/manifest.txt
        echo
        echo "== the synthesized netlist of surfcpu_arty_a7_ddr_bramdiag ($board), nothing on the DDR3L pins: make board-netlist-sim exit $(cat "$t/netlist.rc")"
        echo "   (simulated at source $(cat "$t/netlist.source") in $(cat "$t/netlist.minutes") minutes; the netlist of the open-flow build"
        echo "   at $(sed -n 's/^source_revision = "\(.\{12\}\).*/\1/p' "$m" 2>/dev/null) with BUILD_ID $(sed -n 's/^build_id = "\(.*\)"/\1/p' "$m" 2>/dev/null), its boot ROM inside)"
        grep -E '^netlist_sim: (arty|built in)' "$t/netlist.txt" | sed 's/^/  /'
        n=build/sim/board/netlist/$board-surfcpu_arty_a7_ddr_bramdiag
        grep -q 'Verilator: \$finish' "$n/run.txt" 2>/dev/null ||
            echo "  stopped before its end, after $(grep -o '[0-9]* ms simulated' "$n/run.txt" | tail -n 1): what follows is as far as it went"
        run "$n" "the netlist's run (sim/board/netlist_sim.sh, Verilator)"
    fi
} > "$out"
{
    echo "SurfCPU board track evidence: SurfBoot booting SurfOS on the DDR designs' SoC, EXPECTED FROM"
    echo "SIMULATION with the C++ DDR model (sim/models/ddr_model.h) and LiteDRAM's register model"
    echo "(firmware/tests/ddrc_model.h, surfsim --ddr-swinit: SurfBoot initializes and levels it as on the"
    echo "board), never observed on a board. Generated by sim/board/ddr_sim_evidence.sh (make"
    echo "board-uart-expect-ddr BOARD=$board) on $(date -u +%Y-%m-%d) at source $(cat "$t/source"): the soc"
    echo "track's surfsim with surfcpu_soc as the DDR designs configure it (HAS_DDR 1, DDR_SWINIT 1, the"
    echo "board's BOARD_ID, this commit's BUILD_ID and BUILD_FLAGS), the Arty kernel"
    echo "(../build/riscv32/arty_a7/SURFOS.BIN, make build-kernel) on a tools/mkcard.py card."
    echo "Escape sequences removed, CR removed."
    echo
    echo "make board-uart-expect-ddr: exit $(cat "$t/uart-expect-ddr.rc")"
    grep '^uart_expect_ddr:' "$t/uart-expect-ddr.txt" | sed 's/^/  /'
    echo "-- the UART:"
    sed 's/\x1b\[[0-9;?]*[A-Za-z]//g' build/sim/board/uart_expect_ddr/surfboot.txt | tr -d '\r' | sed 's/^/  | /'
} > "$uout"
echo "ddr_sim_evidence: wrote $out and $uout"
