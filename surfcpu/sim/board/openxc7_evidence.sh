#!/bin/sh
# SurfCPU board track: build the milestone 1 design (arty_a7_baseline) with the open flow for
# both Arty A7 boards, the way the owner would (make build-fpga FLOW=openxc7), and write what
# the builds show into docs/evidence/board/openxc7.txt. On the Mac, from surfcpu/, with Docker
# and the surfcpu-openxc7 image (make openxc7-image); about a minute. The bitstreams stay in
# build/fpga/ (never committed). tools/program.sh is run against the fake openFPGALoader of
# sim/board/tools/fake, so nothing is programmed: it shows only that the files pass its
# header and manifest checks for their board.
set -eu

out=docs/evidence/board/openxc7.txt
design=arty_a7_baseline
t=build/sim/board/openxc7_evidence
rm -rf "$t"
mkdir -p "$t"
rev=$(git rev-parse --short=12 HEAD)
state=clean
[ -z "$(git status --porcelain)" ] || state="dirty (uncommitted changes)"

field() {         # FILE KEY: a string or number from the [openxc7] table of a manifest
    awk -v k="$1" '/^\[openxc7\]/ { s = 1; next } /^\[/ { s = 0 } s && $1 == k && $2 == "=" {
        v = $0; sub(/^[^=]*=[ \t]*/, "", v); gsub(/^"|"$/, "", v); print v; exit }' "$2"
}
top_key() {       # FILE KEY: a top-level value of a manifest
    awk -v k="$1" '/^\[/ { exit } $1 == k && $2 == "=" { v = $0; sub(/^[^=]*=[ \t]*/, "", v); gsub(/^"|"$/, "", v); print v; exit }' "$2"
}

for board in arty_a7_100t arty_a7_35t; do
    t0=$(date +%s)
    if make --no-print-directory build-fpga FLOW=openxc7 BOARD=$board DESIGN=$design > "$t/$board.txt" 2>&1
    then rc=0; else rc=$?; fi
    echo "$(( $(date +%s) - t0 ))" > "$t/$board.seconds"
    echo "$rc" > "$t/$board.rc"
    tail -n 3 "$t/$board.txt"
done

{
    echo "SurfCPU board track evidence: open-flow bitstreams of the milestone 1 design ($design)"
    echo "Generated by sim/board/openxc7_evidence.sh on $(date -u +%Y-%m-%d) at source $rev ($state)."
    echo "Commands: make build-fpga FLOW=openxc7 BOARD=<board> DESIGN=$design, for each board (no build-host.conf)."
    echo "Nothing here was loaded on a board: the physical behaviour of these bitstreams is pending"
    echo "(docs/OPEN-FLOW.md section 8). nextpnr's timing is an estimate, not Vivado signoff."
    for board in arty_a7_100t arty_a7_35t; do
        b=build/fpga/$board/$design
        m=$b/manifest.txt
        ox=$b/openxc7
        echo
        echo "== $board ($(top_key part "$m"); placed and timed as $(field part "$m"))"
        echo "make exit status $(cat "$t/$board.rc"), $(cat "$t/$board.seconds") s; result = $(top_key result "$m")"
        echo "image: $(field image "$m"); $(field yosys "$m" | cut -d'(' -f1)/ $(field nextpnr "$m" | sed 's/.*(\(.*\))/nextpnr-himbaechel \1/')"
        echo "build: $(top_key build_id "$m"), dirty = $(top_key source_dirty "$m"), BUILD_TIME $(top_key build_time "$m")"
        echo "bitstream: $b/$design.bit"
        echo "  $(wc -c < "$b/$design.bit" | tr -d ' ') bytes, sha256 $(shasum -a 256 "$b/$design.bit" | cut -d' ' -f1)"
        echo "  manifest bitstream_sha256 $(top_key bitstream_sha256 "$m")"
        echo "  $(grep '^header:' "$ox/check-bitstream.txt" | sed "s/ date .*,/,/")"
        grep -E '^IDCODE written|^  = |stream [0-9]+ bits|^frame data|^commands|^CRC checks|^check for' "$ox/check-bitstream.txt" | sed 's/^/  /'
        echo "checks (tools/openxc7-build.sh):"
        grep '^check ' "$ox/manifest.txt" | sed 's/^/  /'
        echo "  synthesis: $(grep '^whole design' "$ox/check-synthesis.txt" | tr -s ' ')"
        echo "  LVS: $(grep -E 'proved' "$ox/check-lvs.txt" | tail -n 1)"
        echo "  round trip: $(tail -n 1 "$ox/check-roundtrip.txt")"
        sed 's/^/  clocks: /' "$ox/check-clocks.txt"
        echo "timing (nextpnr):"
        grep -E '^clock |^Hold-fix|^nextpnr warnings' "$ox/timing.txt" | sed 's/^/  /'
        echo "utilization:"
        sed -n '/documented capacity/,/DSP48E1/p' "$ox/utilization.txt" | sed 's/^/  /'
        echo "constraints: nextpnr given $(field constraints_given "$m") lines ($b/nextpnr.xdc); not checked by the open flow:"
        sed 's/^/  /' "$b/nextpnr-not-checked.txt"
        echo "step times:"
        sed 's/^/  /' "$ox/times.txt"
        case "$board" in arty_a7_35t) id=0x0362d093 ;; *) id=0x03631093 ;; esac
        if FAKE_LOG="$t/ofl.log" FAKE_IDCODE=$id OPENFPGALOADER=sim/board/tools/fake/openFPGALoader \
           DESIGN=$design tools/program.sh volatile "$board" > "$t/program-$board.txt" 2>&1
        then prc=0; else prc=$?; fi
        echo "tools/program.sh volatile $board (fake openFPGALoader with the board's IDCODE): exit $prc"
        sed 's/^/  /' "$t/program-$board.txt" | sed "s|$PWD/||"
        echo "  it would run: $(grep -- ' -b ' "$t/ofl.log" | tail -n 1 | sed "s|$PWD/||")"
        other=arty_a7_35t; oid=0x0362d093
        [ "$board" = arty_a7_35t ] && { other=arty_a7_100t; oid=0x03631093; }
        if FAKE_LOG="$t/ofl.log" FAKE_IDCODE=$oid OPENFPGALOADER=sim/board/tools/fake/openFPGALoader \
           tools/program.sh volatile "$other" "$b/$design.bit" > "$t/program-x-$board.txt" 2>&1
        then prc=0; else prc=$?; fi
        echo "the same file on an $other: exit $prc, $(tail -n 1 "$t/program-x-$board.txt" | sed "s|$PWD/||" | sed 's/^program: //')"
    done
} > "$out"
echo "openxc7_evidence: wrote $out"
