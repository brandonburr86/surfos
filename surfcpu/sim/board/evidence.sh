#!/bin/sh
# SurfCPU board track: rerun the board tests and write their short evidence into
# docs/evidence/board/ (make evidence-board, in the toolchain container, from surfcpu/).
# Each file says what was run, with which tools, and the results as the tests printed them.
set -eu

out=docs/evidence/board
b=build/sim/board
mkdir -p "$out"
rev=${SURFCPU_BUILD_ID:-unknown}
tools="$(verilator --version | cut -d' ' -f1-2), $(iverilog -V 2>/dev/null | head -n 1 | cut -d' ' -f1-4), $(yosys -V | cut -d' ' -f1-2), Python $(python3 -c 'import sys; print(sys.version.split()[0])')"

header() {        # FILE TITLE COMMANDS
    {
        echo "SurfCPU board track evidence: $2"
        echo "Generated by sim/board/evidence.sh on $(date -u +%Y-%m-%d) at source $rev; $tools."
        echo "Commands: $3"
        echo "Simulation and static checks only: no bitstream was built and nothing was programmed."
        echo
    } > "$1"
}

make --no-print-directory lint-board > "$b/lint-board.txt" 2>&1
header "$out/lint.txt" "lint" "make lint-board"
cat "$b/lint-board.txt" >> "$out/lint.txt"

make --no-print-directory board-clocks board-prims-bad > "$b/clocks-make.txt" 2>&1
header "$out/clocks.txt" "clock plan, clock tile models, resets" \
    "python3 ip/clocking/clockplan.py report; make board-clocks board-prims-bad"
{
    python3 ip/clocking/clockplan.py report
    echo
    echo "tb_clocks, Icarus:"
    sed 's/^/  /' "$b/tb_clocks.icarus.txt"
    echo "tb_clocks, Verilator --timing:"
    sed 's/^/  /' "$b/tb_clocks.verilator.txt"
    echo
    for n in 1 2 3 4 5 6; do
        printf 'tb_prims_bad case %s: %s\n' "$n" "$(grep -m 1 'FATAL\|fatal\|outside\|not ' "$b/tb_prims_bad.$n.txt" | sed 's/^[[:space:]]*//' | cut -c1-140)"
    done
    tail -n 1 "$b/clocks-make.txt"
} >> "$out/clocks.txt"

make --no-print-directory board-baseline-rt board-baseline > "$b/baseline-make.txt" 2>&1
header "$out/baseline.txt" "milestone 1 baseline in simulation" "make board-baseline-rt board-baseline"
{
    echo "baseline_rt (Verilator, real one-second timing, 2.05 s simulated):"
    sed 's/^/  /' "$b/baseline_rt.txt"
    echo
    echo "tb_baseline (whole top from its pins, clock tile models, 13 ms ticks), Verilator --timing:"
    grep 'tb_baseline:' "$b/tb_baseline.verilator.txt" | sed 's/^/  /'
    echo "tb_baseline, Icarus (+short):"
    grep 'tb_baseline:' "$b/tb_baseline.icarus.txt" | sed 's/^/  /'
} >> "$out/baseline.txt"

make --no-print-directory board-top > "$b/top-make.txt" 2>&1
header "$out/top.txt" "surfcpu_arty_a7_top board wiring" "make board-top (seeds 1 7 123)"
for s in 1 7 123; do
    echo "seed $s:" >> "$out/top.txt"
    grep 'tb_top:' "$b/tb_top.$s.txt" | sed 's/^/  /' >> "$out/top.txt"
done
tail -n 1 "$b/top-make.txt" >> "$out/top.txt"

header "$out/wiring.txt" "pins, WIRING.md, master XDC, I/O timing, CDC names" \
    "python3 tools/check-wiring.py; python3 tools/check-wiring.py --self-test; boards/arty_a7/digilent/fetch.sh verify"
{
    python3 tools/check-wiring.py
    echo
    python3 tools/check-wiring.py --self-test
    echo
    boards/arty_a7/digilent/fetch.sh verify
} >> "$out/wiring.txt"

make --no-print-directory board-cdc-xdc board-tools > "$b/tools-make.txt" 2>&1
header "$out/tools.txt" "Vivado flow, build and program wrappers, CDC constraint logic" \
    "make board-cdc-xdc board-tools (sim/board/tools/cdc_xdc_test.tcl, sim/board/tools/test_tools.sh)"
{
    cat "$b/cdc_xdc_test.txt"
    echo
    cat "$b/test_tools.txt"
} >> "$out/tools.txt"

echo "evidence: wrote $(ls "$out" | tr '\n' ' ')"
