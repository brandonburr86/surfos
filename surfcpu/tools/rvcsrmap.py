#!/usr/bin/env python3
"""
SurfCPU CSR map probe: every CSR address against docs/ISA.md section 2
--------------------
File: rvcsrmap.py Date: 10/15/26 (SurfCPU)
--------------------
Generates a program that reads all 4096 CSR addresses, then writes test patterns to every CSR
of the contract (and to some it does not have) and reads them back, restoring each one. A
trap handler skips the instruction of any illegal access. check() reads a retirement trace
of that program and compares every probe with the contract in tools/rvisa.py: which accesses
trap, which bits stick, what read-only CSRs return. The same check runs on Spike's trace (to
find where Spike differs from our contract, docs/VERIFICATION.md section 4) and on the CPU
testbench's trace (to check SurfCPU against ISA.md directly, without a reference model).

    python3 tools/rvcsrmap.py gen OUT.S                       write the probe program
    python3 tools/rvcsrmap.py check PROBE.elf TRACE [--json F]  compare a trace with ISA.md
    python3 tools/rvcsrmap.py spike [--build DIR] [-v] [--stock]
        build, run on the reference Spike: the contract-patched one must agree with
        docs/ISA.md on every probe; the stock one (--stock) must differ exactly in the
        known ways (SPIKE_KNOWN)

Exit status of check/spike: 0 when every probe matches the contract, 1 otherwise.
Only the Python standard library is used.
"""

from __future__ import annotations

import argparse
import collections
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import rvelf      # noqa: E402
import rvisa      # noqa: E402
import tracefmt   # noqa: E402

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
LINK_LD = ROOT / "sim" / "ref" / "common" / "link.ld"

PATTERNS = (0xFFFFFFFF, 0x00000000, 0xA5A5A5A5, 0x5A5A5A5A)
# mcause is WLRL: only legal values must read back (docs/ISA.md section 2).
MCAUSE_PATTERNS = (0x0000000B, 0x80000007, 0x00000002, 0x8000000B)


def patterns_for(addr: int) -> tuple[int, ...]:
    return MCAUSE_PATTERNS if addr == 0x342 else PATTERNS
# Counters: written and read back immediately, so no instruction retires in between.
COUNTERS = {0xB00, 0xB02, 0xB80, 0xB82}
# Values the read sweep cannot predict (changed by earlier probes' traps, or by time).
UNPREDICTABLE_READ = {0x341, 0x342, 0x343}
# CSRs SurfCPU does not have, written anyway (they must trap): one of each family.
EXTRA_WRITES = [0x000, 0x001, 0x100, 0x105, 0x140, 0x180, 0x302, 0x303, 0x306, 0x30A,
                0x34A, 0x7A0, 0x7A1, 0x7B0, 0x747, 0x7C0, 0x800, 0xBC0, 0xCC0, 0xFC0]


def write_set() -> list[int]:
    return sorted(set(rvisa.CSRS) | set(EXTRA_WRITES))


def generate() -> str:
    out = [
        "# SurfCPU CSR map probe, generated by tools/rvcsrmap.py: do not edit.",
        "    .section .text.init, \"ax\"",
        "    .globl _start",
        "_start:",
        "    la t0, csr_trap",
        "    csrw mtvec, t0",
        "# 1. read every CSR address (csrrs x5, csr, x0)",
    ]
    for a in range(4096):
        out += [f"    li x5, 0x5eed{a:04x}", f"p_r_{a:03x}: csrrs x5, 0x{a:03x}, x0"]
    out.append("# 2. write patterns and read back, then restore")
    for a in write_set():
        if a in (0x305,):
            continue           # mtvec: tested last (the handler must stay reachable)
        out.append(f"    csrrs x6, 0x{a:03x}, x0")
        for k, pat in enumerate(patterns_for(a)):
            out += [f"    li x7, 0x{pat:08x}",
                    f"p_w_{a:03x}_{k}: csrrw x0, 0x{a:03x}, x7",
                    f"p_b_{a:03x}_{k}: csrrs x5, 0x{a:03x}, x0"]
        out.append(f"    csrrw x0, 0x{a:03x}, x6")
    # mtvec: the patterns, restoring the handler right after each read-back.
    out += ["    la x6, csr_trap"]
    for k, pat in enumerate(PATTERNS):
        out += [f"    li x7, 0x{pat:08x}",
                f"p_w_305_{k}: csrrw x0, mtvec, x7",
                f"p_b_305_{k}: csrrs x5, mtvec, x0",
                "    csrw mtvec, x6"]
    out.append("# 3. what counts as a write: read-only CSRs with rs1/uimm zero and non-zero")
    for a in (0xF11, 0xF14, 0xC00, 0xC02):
        out += [f"    li x8, 0",
                f"p_x_{a:03x}_0: csrrs x5, 0x{a:03x}, x0",
                f"p_x_{a:03x}_1: csrrsi x5, 0x{a:03x}, 0",
                f"p_x_{a:03x}_2: csrrc x5, 0x{a:03x}, x0",
                f"p_x_{a:03x}_3: csrrci x5, 0x{a:03x}, 0",
                f"p_x_{a:03x}_4: csrrs x5, 0x{a:03x}, x8",
                f"p_x_{a:03x}_5: csrrsi x5, 0x{a:03x}, 1",
                f"p_x_{a:03x}_6: csrrw x5, 0x{a:03x}, x0",
                f"p_x_{a:03x}_7: csrrwi x5, 0x{a:03x}, 0"]
    out += [
        "    li t0, 1",
        "    la t1, tohost",
        "1:  sw t0, 0(t1)",
        "    j 1b",
        "    .balign 4",
        "csr_trap:",
        "    csrr t6, mepc",
        "    addi t6, t6, 4",
        "    csrw mepc, t6",
        "    mret",
        "    .section .tohost, \"aw\", @progbits",
        "    .balign 64",
        "    .globl tohost",
        "tohost: .dword 0",
        "    .balign 64",
        "    .globl fromhost",
        "fromhost: .dword 0",
    ]
    return "\n".join(out) + "\n"


# Which probes write (p_x_* variants 0..7: csrrs x0, csrrsi 0, csrrc x0, csrrci 0 read;
# csrrs x8 (=0), csrrsi 1, csrrw x0, csrrwi 0 write).
_X_WRITES = {0: False, 1: False, 2: False, 3: False, 4: True, 5: True, 6: True, 7: True}


def check(elf_path: Path, trace_path: Path) -> dict:
    """Compare one trace of the probe program with the contract. Returns a report dict."""
    elf = rvelf.read_elf(elf_path)
    recs = tracefmt.read_trace(trace_path)
    by_pc: dict[int, tracefmt.Rec] = {}
    for r in recs:
        by_pc.setdefault(r.pc, r)          # each probe runs once
    issues: list[dict] = []
    counts = {"read": 0, "write": 0, "rule": 0}
    handler = elf.symbol("csr_trap")

    def rec_for(label: str) -> tracefmt.Rec | None:
        return by_pc.get(elf.symbol(label))

    def issue(csr, probe, expected, observed):
        issues.append({"csr": f"0x{csr:03x}", "name": rvisa.csr_name(csr), "probe": probe,
                       "expected": expected, "observed": observed})

    def outcome(r: tracefmt.Rec | None) -> str:
        if r is None:
            return "not executed"
        return "trap" if r.trap else f"{r.rd_wdata:08x}"

    # 1. reads
    for a in range(4096):
        counts["read"] += 1
        r = rec_for(f"p_r_{a:03x}")
        c = rvisa.CSRS.get(a)
        exp_trap = not rvisa.csr_access(a, False)
        got = outcome(r)
        if exp_trap:
            if got != "trap":
                issue(a, "read", "trap", got)
            continue
        if got == "trap" or got == "not executed":
            issue(a, "read", "no trap", got)
            continue
        if c.timing or a in COUNTERS or a in (0xC02, 0xC82) or a in UNPREDICTABLE_READ:
            continue
        if a == 0x305:
            if r.rd_wdata != handler:
                issue(a, "read", f"{handler:08x}", got)
        elif c.wmask:
            # Writable CSRs: earlier probes' traps and MRETs change the writable bits
            # (mstatus.MPIE); only the fixed bits are known.
            if r.rd_wdata & ~c.wmask != c.fixed & ~c.wmask:
                issue(a, "read (fixed bits)", f"{c.fixed & ~c.wmask:08x}",
                      f"{r.rd_wdata & ~c.wmask:08x}")
        elif c.reset is not None and r.rd_wdata != c.reset:
            issue(a, "read", f"{c.reset:08x}", got)
    # 2. writes and read-backs
    for a in write_set():
        c = rvisa.CSRS.get(a)
        exp_trap = not rvisa.csr_access(a, True)
        for k, pat in enumerate(patterns_for(a)):
            counts["write"] += 1
            w = rec_for(f"p_w_{a:03x}_{k}")
            b = rec_for(f"p_b_{a:03x}_{k}")
            gw = outcome(w)
            if exp_trap:
                if gw != "trap":
                    issue(a, f"write {pat:08x}", "trap", gw)
                continue
            if gw == "trap" or gw == "not executed":
                issue(a, f"write {pat:08x}", "no trap", gw)
                continue
            gb = outcome(b)
            if gb in ("trap", "not executed"):
                issue(a, f"read-back after {pat:08x}", "a value", gb)
                continue
            if c.timing:
                continue
            if a in COUNTERS:
                exp = pat
            elif c.wmask == 0:
                exp = c.reset if a != 0x305 else None
            else:
                base = c.fixed if c.fixed is not None else 0
                exp = (base & ~c.wmask | pat & c.wmask) & 0xFFFFFFFF
            if exp is not None and b.rd_wdata != exp:
                issue(a, f"read-back after {pat:08x}", f"{exp:08x}", gb)
    # 3. what counts as a write
    for a in (0xF11, 0xF14, 0xC00, 0xC02):
        for v, writes in _X_WRITES.items():
            counts["rule"] += 1
            r = rec_for(f"p_x_{a:03x}_{v}")
            got = outcome(r)
            exp = "trap" if writes else "no trap"
            if (got == "trap") != writes or got == "not executed":
                issue(a, f"rule variant {v}", exp, got)
    return {"elf": str(elf_path), "trace": str(trace_path), "probes": counts,
            "issues": issues}


# Where the pinned Spike, configured as tools/trace_spike.py does, differs from docs/ISA.md
# (docs/VERIFICATION.md section 4). `spike` fails if Spike shows a difference that is not
# here, or no longer shows one that is.
SPIKE_KNOWN = {
    "pmp": "pmpcfg0-15 and pmpaddr0-63 are illegal on Spike with --pmpregions=0; the "
           "contract has them as read-only zero",
    "triggers": "tselect, tdata1-3, tinfo and mcontext exist on Spike even with "
                "--triggers=0; SurfCPU has no trigger CSRs (illegal)",
    "marchid": "marchid is 5 on Spike (its registered id); 0 on SurfCPU",
    "mimpid": "mimpid is 0 on Spike; 0x00000100 on SurfCPU",
    "misa": "writes to misa can clear M on Spike; SurfCPU ignores them",
    "mtvec": "mtvec MODE bit 0 (vectored) sticks on Spike; SurfCPU's MODE is fixed at 0",
    "mcountinhibit": "mcountinhibit bits 3-31 (hpm counters) are writable on Spike with "
                     "Zihpm; SurfCPU has only CY and IR",
}


def classify_spike(issue: dict) -> str | None:
    a = int(issue["csr"], 16)
    exp, obs = issue["expected"], issue["observed"]
    if 0x3A0 <= a <= 0x3EF and exp == "no trap" and obs == "trap":
        return "pmp"
    if a in (0x7A0, 0x7A1, 0x7A2, 0x7A3, 0x7A4, 0x7A8) and exp == "trap" and obs != "trap":
        return "triggers"
    if a == 0xF12 and issue["probe"] == "read" and obs == "00000005":
        return "marchid"
    if a == 0xF13 and issue["probe"] == "read" and obs == "00000000":
        return "mimpid"
    if a == 0x301 and issue["probe"].startswith("read-back") and obs == "40000100":
        return "misa"
    if a == 0x305 and issue["probe"].startswith("read-back") and \
            int(obs, 16) == int(exp, 16) | 1:
        return "mtvec"
    if a == 0x320 and issue["probe"].startswith("read-back") and \
            int(obs, 16) & 7 == int(exp, 16) & 7:
        return "mcountinhibit"
    return None


def check_spike_known(rep: dict) -> list[str]:
    """Problems with the known-difference list: unexplained issues, unused rules."""
    used = set()
    problems = []
    for i in rep["issues"]:
        rule = classify_spike(i)
        if rule is None:
            problems.append(f"unexplained: {i['csr']} {i['name']} {i['probe']}: contract "
                            f"{i['expected']}, Spike {i['observed']}")
        else:
            used.add(rule)
    for rule in sorted(set(SPIKE_KNOWN) - used):
        problems.append(f"known difference {rule!r} no longer seen: update "
                        "tools/rvcsrmap.py and docs/VERIFICATION.md")
    return problems


def print_report(rep: dict, who: str) -> None:
    n = sum(rep["probes"].values())
    print(f"rvcsrmap: {who}: {n} probes ({rep['probes']['read']} reads, "
          f"{rep['probes']['write']} writes, {rep['probes']['rule']} write-rule checks), "
          f"{len(rep['issues'])} differ from docs/ISA.md")
    for i in rep["issues"]:
        print(f"  {i['csr']} {i['name']:<14} {i['probe']:<28} contract {i['expected']:<10} "
              f"observed {i['observed']}")


def build(asm: Path, elf: Path) -> None:
    subprocess.run(["riscv64-unknown-elf-gcc", "-march=rv32im_zicsr_zifencei", "-mabi=ilp32",
                    "-nostdlib", "-nostartfiles", "-Wl,--no-warn-rwx-segments", "-T",
                    str(LINK_LD), "-o", str(elf), str(asm)], check=True)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen")
    g.add_argument("out")
    c = sub.add_parser("check")
    c.add_argument("elf")
    c.add_argument("trace")
    c.add_argument("--json")
    s = sub.add_parser("spike")
    s.add_argument("--build", default=str(ROOT / "build" / "ref" / "csrmap"))
    s.add_argument("--json")
    s.add_argument("-v", "--verbose", action="store_true", help="list every difference")
    s.add_argument("--stock", action="store_true",
                   help="use the container's stock Spike, not the contract-patched one")
    a = ap.parse_args(argv)
    if a.cmd == "gen":
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(generate())
        return 0
    if a.cmd == "check":
        rep = check(Path(a.elf), Path(a.trace))
        print_report(rep, a.trace)
    else:
        import trace_spike
        d = Path(a.build)
        d.mkdir(parents=True, exist_ok=True)
        asm, elf, trace = d / "csrmap.S", d / "csrmap.elf", d / "csrmap.spike.trace"
        asm.write_text(generate())
        build(asm, elf)
        binary = "spike" if a.stock else None
        res = trace_spike.run_spike(elf, binary=binary)
        if res.status != "pass":
            print(f"rvcsrmap: the probe did not finish on Spike ({res.status})")
            return 1
        tracefmt.save_trace(res.records, trace, trace_spike.trace_comments(res, elf))
        rep = check(elf, trace)
        if a.verbose:
            print_report(rep, "Spike (" + " ".join(res.command[1:6]) + ")")
        n = sum(rep["probes"].values())
        stock = a.stock or trace_spike.SPIKE_KIND == "stock"
        if stock:
            # The stock Spike must differ from the contract exactly in the known ways.
            problems = check_spike_known(rep)
            counts = collections.Counter(classify_spike(i) for i in rep["issues"])
            print(f"rvcsrmap: stock Spike: {n} probes; {len(rep['issues'])} differ from "
                  "docs/ISA.md" + (", all of them known:" if not problems else ":"))
            for rule, text in SPIKE_KNOWN.items():
                print(f"  {rule:<14} {counts.get(rule, 0):>4} probes  {text}")
        else:
            # The contract-patched Spike must agree with the contract on every probe.
            problems = [f"{i['csr']} {i['name']} {i['probe']}: contract {i['expected']}, "
                        f"Spike {i['observed']}" for i in rep["issues"]]
            print(f"rvcsrmap: Spike with surfcpu-contract.patch: {n} probes, "
                  f"{len(rep['issues'])} differ from docs/ISA.md")
        for p in problems:
            print("  PROBLEM: " + p)
        if a.json:
            Path(a.json).parent.mkdir(parents=True, exist_ok=True)
            Path(a.json).write_text(json.dumps(rep, indent=1) + "\n")
        return 1 if problems else 0
    if a.json:
        Path(a.json).parent.mkdir(parents=True, exist_ok=True)
        Path(a.json).write_text(json.dumps(rep, indent=1) + "\n")
    return 0 if not rep["issues"] else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
