/*
SurfCPU Arty A7 clocks and resets
--------------------
File: arty_a7_clocks.v Date: 10/15/26 (SurfCPU)
--------------------
The SoC's two clocks from the board's 100 MHz oscillator, made by AMD clock tiles, and one
synchronous active-high reset per clock domain (docs/BOARD.md sections 2 and 3):

  sys_clk  clocks.sys_hz  PLLE2_BASE   100 MHz x 10 / 40      (VCO 1000 MHz)
  pix_clk  clocks.pix_hz  MMCME2_BASE  100 MHz x 8.875 / 35.25 (VCO 887.5 MHz)

The settings come from arty_a7_clock_params.vh, generated by ip/clocking/clockplan.py, which
checks them against the 7-series limits of both Arty parts and against spec/soc.toml. Each
tile's feedback is internal (CLKFBOUT straight to CLKFBIN): nothing here needs its clocks
phase-aligned to the oscillator pin. Each output reaches its domain through a BUFG.

Resets: a domain's reset asserts asynchronously while its tile is unlocked or rst_btn is 1, and
surf_reset_sync releases it on that domain's own clock. rst_btn also resets both tiles (the
RESET button is how to recover a tile that has lost lock; UG472 says a tile must be reset
after LOCKED falls). Vendor primitives: this file belongs under boards/ only.
*/
module arty_a7_clocks (
    input  wire clk100,      // the 100 MHz oscillator (pin E3)
    input  wire rst_btn,     // 1 = reset (the RESET button, inverted), asynchronous
    output wire sys_clk,
    output wire sys_rst,     // synchronous to sys_clk, active high
    output wire pix_clk,
    output wire pix_rst,     // synchronous to pix_clk, active high
    output wire sys_locked,
    output wire pix_locked
);
    `include "arty_a7_clock_params.vh"

    // The tiles' unused outputs are left open on purpose (the waiver covers the two instances).
    /* verilator lint_off PINCONNECTEMPTY */

    // ---------------------------------------------------------------- sys_clk: PLL
    wire sys_clk_unbuf;
    wire sys_fb;

    PLLE2_BASE #(
        .BANDWIDTH          ("OPTIMIZED"),
        .CLKIN1_PERIOD      (ARTY_CLKIN_PERIOD_NS),
        .DIVCLK_DIVIDE      (ARTY_SYS_DIVCLK_DIVIDE),
        .CLKFBOUT_MULT      (ARTY_SYS_CLKFBOUT_MULT),
        .CLKFBOUT_PHASE     (0.0),
        .CLKOUT0_DIVIDE     (ARTY_SYS_CLKOUT0_DIVIDE),
        .CLKOUT0_DUTY_CYCLE (0.5),
        .CLKOUT0_PHASE      (0.0),
        .STARTUP_WAIT       ("FALSE")
    ) u_sys_pll (
        .CLKIN1   (clk100),
        .CLKFBIN  (sys_fb),
        .CLKFBOUT (sys_fb),
        .CLKOUT0  (sys_clk_unbuf),
        .CLKOUT1  (),
        .CLKOUT2  (),
        .CLKOUT3  (),
        .CLKOUT4  (),
        .CLKOUT5  (),
        .LOCKED   (sys_locked),
        .PWRDWN   (1'b0),
        .RST      (rst_btn)
    );

    BUFG u_sys_bufg (.I(sys_clk_unbuf), .O(sys_clk));

    // ---------------------------------------------------------------- pix_clk: MMCM
    wire pix_clk_unbuf;
    wire pix_fb;

    MMCME2_BASE #(
        .BANDWIDTH          ("OPTIMIZED"),
        .CLKIN1_PERIOD      (ARTY_CLKIN_PERIOD_NS),
        .DIVCLK_DIVIDE      (ARTY_PIX_DIVCLK_DIVIDE),
        .CLKFBOUT_MULT_F    (ARTY_PIX_CLKFBOUT_MULT_F),
        .CLKFBOUT_PHASE     (0.0),
        .CLKOUT0_DIVIDE_F   (ARTY_PIX_CLKOUT0_DIVIDE_F),
        .CLKOUT0_DUTY_CYCLE (0.5),
        .CLKOUT0_PHASE      (0.0),
        .STARTUP_WAIT       ("FALSE")
    ) u_pix_mmcm (
        .CLKIN1    (clk100),
        .CLKFBIN   (pix_fb),
        .CLKFBOUT  (pix_fb),
        .CLKFBOUTB (),
        .CLKOUT0   (pix_clk_unbuf),
        .CLKOUT0B  (),
        .CLKOUT1   (),
        .CLKOUT1B  (),
        .CLKOUT2   (),
        .CLKOUT2B  (),
        .CLKOUT3   (),
        .CLKOUT3B  (),
        .CLKOUT4   (),
        .CLKOUT5   (),
        .CLKOUT6   (),
        .LOCKED    (pix_locked),
        .PWRDWN    (1'b0),
        .RST       (rst_btn)
    );

    /* verilator lint_on PINCONNECTEMPTY */

    BUFG u_pix_bufg (.I(pix_clk_unbuf), .O(pix_clk));

    // ---------------------------------------------------------------- resets
    surf_reset_sync u_sys_rst (.clk(sys_clk), .arst(!sys_locked || rst_btn), .rst(sys_rst));
    surf_reset_sync u_pix_rst (.clk(pix_clk), .arst(!pix_locked || rst_btn), .rst(pix_rst));
endmodule
