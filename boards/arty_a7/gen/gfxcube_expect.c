/*
SurfOS board: SurfCPU on the Arty A7 -- gfx cube's expected frames
--------------------
File: gfxcube_expect.c  Date: 10/26/26 (SurfGPU, the cube in SurfOS)
--------------------
  gfxcube_expect > gfxcube_expect.h

A host tool of the Arty kernel's build (arch/riscv32/kernel.mk) and of its host test
(surfcpu/mk/area-gpuos.mk). It draws gpudiag's spinning cube with the same commands SurfOS's gfx
cube sends, gpu_cube_frame() of surfcpu/firmware/diagnostics/gpucube.c, through the C model of the
engine (surfcpu/sim/models/gpu_model.c), and writes the FRAME_CRC of each of the 128 frames of a
turn as gfx cube's display shows it (surfcpu/docs/GPU.md 15.8): frame k drawn into picture A (k
even) or B (k odd) of GPU.md 16.6's layout, shown in CTRL.MODE 2, graphics alone, at GFX_STRIDE 320
and GFX_SCALE 2, from the base its FLIP gives, through the palette gpu_cube_display() loads (only
its GPAL is taken, as gfx cube takes it). Nothing of SurfOS's driver or gfx command is used: this
table is what they are checked against, on the board and on the RTL system.

It also counts the pictures that differ, GFX_CUBE_PICTURES: gfx cube checks the order of the
frames shown only when all 128 do. Exit status 1, and no table, when a frame leaves the engine
inside a command, with an error, with a FLIP to the wrong picture or its FENCE not done, or when
the model's clamp or widths were needed (GPU.md 16.4 says they never are).
*/

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "gpu_model.h"
#include "gpucube.h"
#include "surfcpu/soc.h"

static uint8_t vram[GPU_VRAM_BYTES];
static struct gpu_engine eng;
static struct gpu_display disp;
static uint16_t frame[GPU_SCREEN_W * GPU_SCREEN_H];
static const uint8_t nofont[256][16];   /* MODE 2 shows no text: the text layer is not looked at */
static unsigned odd;

static void m_cmd(uint32_t w) { gpu_engine_word(&eng, w); }
static void m_sync(void) {}
static void m_vram32(uint32_t off, uint32_t v) { (void)off; (void)v; odd++; }
static void m_vram8(uint32_t off, uint32_t v) { (void)off; (void)v; odd++; }
static void m_video(uint32_t off, uint32_t v) {
    if(off >= SURF_VIDEO_GPAL && off < SURF_VIDEO_GPAL + 4u * SURF_VIDEO_GPAL_COUNT)
        disp.gpal[(off - SURF_VIDEO_GPAL) / 4] = (uint16_t)(v & 0xFFFu);
}
static void m_text(uint32_t cell, uint32_t v) { (void)cell; (void)v; }
static const struct gpu_sink sink = { m_cmd, m_sync, m_vram32, m_vram8, m_video, m_text };

int main(void) {
    uint32_t crc[GPU_CUBE_PERIOD];
    unsigned k, j, pictures = 0, problems = 0;
    gpu_engine_init(&eng, vram);
    gpu_display_reset(&disp, 1);
    gpu_cube_display(&sink, 0);                     /* its palette; the rest of its display is not SurfOS's */
    disp.enable = 1;                                /* gfx cube's display (GPU.md 15.8) */
    disp.mode = 2;
    disp.cursor = 0;
    disp.gfx_stride = 320;
    disp.gfx_scale = 2;
    for(k = 0; k < GPU_CUBE_PERIOD; k++) {
        unsigned flips = eng.flips;
        gpu_cube_frame(&sink, k, k & 1u, k + 1u);
        if(!gpu_engine_idle(&eng) || (eng.sticky & (GPU_ST_BAD_OPCODE | GPU_ST_BAD_PARAM)) || eng.flips != flips + 1 ||
           eng.flip_base != ((k & 1u) ? GPU_CUBE_B : GPU_CUBE_A) || eng.fence != k + 1u) {
            fprintf(stderr, "gfxcube_expect: frame %u leaves the engine wrong\n", k);
            problems++;
        }
        disp.gfx_base = eng.flip_base;              /* what its FLIP shows from the next frame */
        gpu_display_render(&disp, vram, NULL, nofont, frame);
        crc[k] = gpu_frame_crc(frame);
    }
    if(odd || eng.tri_clamped || eng.tri_wide) {
        fprintf(stderr, "gfxcube_expect: %u VRAM writes through the sink, the model's clamp changed %llu values, "
                "%llu were wide\n", odd, eng.tri_clamped, eng.tri_wide);
        problems++;
    }
    if(problems) return 1;
    for(k = 0; k < GPU_CUBE_PERIOD; k++) {
        for(j = 0; j < k && crc[j] != crc[k]; j++) {}
        pictures += j == k;
    }
    printf("/* generated by boards/arty_a7/gen/gfxcube_expect.c from gpucube.c and the C model -- do not edit:\n"
           "   the FRAME_CRC of each frame of a turn of gpudiag's cube as gfx cube shows it (GPU.md 15.8) */\n"
           "#define GFX_CUBE_FRAMES %uu\n#define GFX_CUBE_PICTURES %uu        /* of them, pictures of their own */\n",
           GPU_CUBE_PERIOD, pictures);
    for(k = 0; k < GPU_CUBE_PERIOD; k++)
        for(j = 0; j < k; j++)
            if(crc[j] == crc[k]) printf("/* frames %u and %u are the same picture */\n", j, k);
    printf("static const uint32_t gfx_cube_expect[GFX_CUBE_FRAMES] = {\n");
    for(k = 0; k < GPU_CUBE_PERIOD; k += 4)
        printf("    0x%08xu, 0x%08xu, 0x%08xu, 0x%08xu,     /* %3u-%3u */\n", crc[k], crc[k + 1], crc[k + 2], crc[k + 3], k,
               k + 3);
    printf("};\n");
    return 0;
}
