#!/usr/bin/env python3
"""Make the width table of the web browser's proportional text from the console's own fonts.

    tools/fontmetrics.py > user/wundertow/fontmetrics.c

The glyphs of driver/font8x16.c, font12x24.c and font16x32.c, trimmed to their ink: for each of a font's 256 cells,
the first column with ink in it (the bearing, how far left of its place a cell is drawn) and how far the next
character is from this one (the advance): the ink's width and a gap of a sixth of the cell. So no new font data and no
new licence: Spleen's glyphs are drawn as they are, nearer together. A different font needs the owner's word (the brief,
docs/superpowers/plans/2026-11-01-browser-m2-m3.md).

An empty cell is half a cell wide, a space's width. What must meet its neighbours stays a whole cell: the box drawing,
shades and blocks of code page 437, 0xB0 to 0xDF. Monospaced text does not come here at all: it stays in its cells.

Run by hand when a font changes, as tools/bdf2c.py is; test_wundertow_layout checks the table against the fonts.
gui_apps_web.py uses metrics() for where text is on the screen.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = ('8x16', '12x24', '16x32')


def rows(name):
    """{index: its rows} of a font, each row an integer of the cell's width, the leftmost pixel highest"""
    width = int(name.split('x')[0])
    shift = (8 if width <= 8 else 16) - width
    with open(os.path.join(ROOT, 'driver', f'font{name}.c'), encoding='utf-8') as f:
        src = f.read()
    entries = re.findall(r'\[0x([0-9a-fA-F]{2})\] = \{ ([^}]*) \}', src)
    if len(entries) != 256:
        sys.exit(f'font{name}.c: {len(entries)} of 256 entries')
    return {int(i, 16): [int(v, 16) >> shift for v in values.split(',')] for i, values in entries}


def metrics(name):
    """[(bearing, advance)] for the 256 cells of a font"""
    width = int(name.split('x')[0])
    gap = (width + 3) // 6
    table = []
    glyphs = rows(name)
    for index in range(256):
        ink = 0
        for row in glyphs[index]:
            ink |= row
        columns = [c for c in range(width) if ink & (1 << (width - 1 - c))]
        if 0xb0 <= index <= 0xdf:
            table.append((0, width))
        elif not columns:
            table.append((0, width // 2))
        else:
            table.append((columns[0], columns[-1] - columns[0] + 1 + gap))
    return table


def main():
    print('''/*
SurfOS Undertow's window: the width of each glyph of the console's fonts
----------------------
File: fontmetrics.c  Date: 11/01/26; generated by tools/fontmetrics.py
----------------------
font.h's proportional text: for each cell of driver/font8x16.c, font12x24.c and font16x32.c, its first column with ink
in it and how far on the next character goes. Numbers made from those fonts' glyphs, Spleen by Frederic Cambus and
SurfOS's symbols (driver/fonts/LICENSE-spleen), which are drawn as they are.
*/

#include "font.h"

const struct wf_metric wf_metrics[3][256] = {''')
    for name in FONTS:
        print(f'    {{   /* {name} */')
        table = metrics(name)
        for i in range(0, 256, 8):
            print('        ' + ' '.join('{ %d, %d },' % table[k] for k in range(i, i + 8)))
        print('    },')
    print('};')


if __name__ == '__main__':
    main()
